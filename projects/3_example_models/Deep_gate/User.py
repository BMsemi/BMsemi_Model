"""
QuantLinear inference pipeline using neuromorphic hardware simulation.

- Model weights and quantisation parameters loaded from schema.json
- Test inputs and expected outputs loaded from test_cases.json
- Per-layer tile mapping parsed from schema_10layer_mapping_fc.m via
  MaestroClusterMapper; weight-programming ops generated by
  MaestroClusterScheduler
- Physical crossbar is 32×32; weight tiles are clipped to that size and
  programmed onto MultiPENeuromorphicCore PEs as signed INT8 (PWM row-serial
  mode with internal 4-way split: pos0/pos1/neg0/neg1)
- Exact int8 fixed-point output produced by
  torch_quantised_linear_forward_vectorised (sat_round_doubling_high_mul
  + round_shift_right), independent of the hardware simulation
- Intermediate activations stored in L2_Buffer between layers
"""

import json
import sys
import io
import numpy as np
from pathlib import Path

from Mapper import MaestroClusterMapper
from Scheduler import MaestroClusterScheduler
from Multi_PE_Core import MultiPENeuromorphicCore
from L2_Buffer import L2_Buffer
from LatencyObjective import (
    LatencyModelConfig,
    estimate_fc_latency_objective,
    estimate_latency_objective,
)
from torch_quantised_linear import torch_quantised_linear_forward_vectorised

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')

# Physical crossbar tile dimension (rows = columns = 32)
TILE = 32

# Set to a layer index (0-9) to verify a single layer before running the full
# pipeline.  Set to None to run all 10 layers.
VERIFY_LAYER: int | None = None

# When True, write per-layer detailed logs under ./layer_logs on each run.
GENERATE_LAYER_LOGS: bool = True

# Enforce that hardware programming uses signed INT8 PWM mode (4-way split
# into pos0/pos1/neg0/neg1 inside CrossbarArray).
ENFORCE_PWM_MODE: bool = True

# Dynamic weights require the same crossbar/cluster to be reprogrammed before
# the next inference tile. When enabled, latency is modeled as repeated
# program -> inference -> program waves instead of one static preload.
DYNAMIC_WEIGHT_REPROGRAMMING: bool = True

LATENCY_CONFIG = LatencyModelConfig(
    dynamic_weight_reprogramming=DYNAMIC_WEIGHT_REPROGRAMMING
)


def _arr_to_str(arr: np.ndarray) -> str:
    """Stable, high-precision array formatting for log files."""
    return np.array2string(
        arr,
        precision=17,
        floatmode='unique',
        separator=', ',
        max_line_width=200000,
    )


# =====================================================
# Data Loading
# =====================================================

def load_schema(schema_path: str) -> list:
    """Load list of QuantLinear layer specs from schema.json."""
    with open(schema_path, 'r') as f:
        return json.load(f)


def load_test_cases(test_path: str) -> dict:
    """Load test-case dictionary from test_cases.json."""
    with open(test_path, 'r') as f:
        return json.load(f)


# =====================================================
# Layer Parameter Parsing
# =====================================================

def parse_layer(layer: dict) -> dict:
    """
    Extract weight tensors and quantisation parameters from a schema layer dict.

    Returns a flat dict with all tensors as NumPy arrays, ready for inference.
    """
    specs = layer['module_specs']
    shape_in = layer['shape_in'][0]
    shape_out = layer['shape_out'][0]

    W_data = specs['weights_int8']['data']
    if W_data:
        W_int8 = np.array(W_data, dtype=np.int8).reshape(shape_out, shape_in)
    else:
        W_int8 = np.zeros((shape_out, shape_in), dtype=np.int8)

    return {
        'shape_in':      shape_in,
        'shape_out':     shape_out,
        'W_int8':        W_int8,
        'bias_int32':    np.array(specs['bias_int32']['data'],          dtype=np.int32),
        'weight_scales': np.array(specs['weight_scales']['data'],       dtype=np.float32),
        'input_scale':   float(specs['input_scale']['data']),
        'input_zp':      int(specs['input_zp']['data']),
        'output_scale':  float(specs['output_scale']['data']),
        'output_zp':     int(specs['output_zp']['data']),
        'requant_mult':  np.array(specs['requant_multiplier']['data'],  dtype=np.int32),
        'requant_shift': np.array(specs['requant_shift']['data'],       dtype=np.int32),
        'act_func':      specs.get('act_func'),
        'input_no_quant': specs.get('input_no_quant', False),
    }


# =====================================================
# Weight Provider
# =====================================================

def make_weight_provider(params: dict):
    """
    Build a weight_provider(k0, kN) compatible with
    MaestroClusterScheduler.iter_ops.

    For a fully-connected layer the int8 weight matrix is W[K, C].
    The scheduler expects shape (patch_len, kN-k0) = (C, kN-k0):
        weight_provider(k0, kN) → W[k0:kN, :].T  cast to float32.
    """
    W  = params['W_int8']   # (K, C) int8
    K, C = W.shape

    def weight_provider(k0: int, kN: int) -> np.ndarray:
        k0  = int(k0)
        kN  = min(int(kN), K)
        cols = kN - k0
        out  = np.zeros((C, cols), dtype=np.float32)
        if k0 < kN:
            out[:, :cols] = W[k0:kN, :].T.astype(np.float32)
        return out

    return weight_provider


# =====================================================
# Single-Layer Execution
# =====================================================

def execute_quant_linear(
    layer_idx: int,
    params: dict,
    x_int8: np.ndarray,
    mapping_file: str,
    mpe: MultiPENeuromorphicCore,
    l2_buffer: L2_Buffer,
    verbose: bool = False,
) -> tuple:
    """
    Execute one QuantLinear layer.

    Hardware mapping (simulation)
    -----------------------------
    MaestroClusterMapper parses the per-layer entry in the .m file to obtain
    K-chunks, C-fold sizes and cluster configuration (e.g. Cluster(64,P)).
    MaestroClusterScheduler.iter_ops streams PROGRAM_CLUSTER and
    COMPUTE_CLUSTER_C ops driven by that mapping.

    For each PROGRAM_CLUSTER op the scheduler provides a tile; we cast that
    tile to signed INT8 and program the PE so CrossbarArray selects
    PWM_INT8_ROW_SERIAL mode (the internal 4-way split banks).

    For each COMPUTE_CLUSTER_C op we build a TILE-element uint8 activation
    slice (clipped to [0,255]) and call mpe.compute_pe_fast for PE-utilisation
    tracking.

    Exact quantised arithmetic
    --------------------------
    torch_quantised_linear_forward_vectorised computes the correct int8 output
    (sat_round_doubling_high_mul + round_shift_right) on the full (K×C) weight
    matrix and x_adj.  This is independent of and always consistent with the
    hardware simulation above.

    L2 Buffer
    ---------
    The float32 dequantised output is stored as a single 1-D channel.
    The previous layer's entry is evicted immediately after writing.

    Returns
    -------
    y_float : (shape_out,) float32 dequantised activation
    y_int8  : (shape_out,) int8 activation (input to next layer)
    stats   : dict - ops / num_weights / active_pes / util_pct
    """
    shape_in  = params['shape_in']
    shape_out = params['shape_out']
    input_zp  = params['input_zp']
    output_zp = params['output_zp']

    # ------------------------------------------------------------------
    # 1. Zero-point adjustment
    # ------------------------------------------------------------------
    # The provided test vectors are already quantized-domain activations;
    # zero-point correction must be applied for all layers (including FC0).
    x_adj = x_int8.astype(np.int32) - input_zp

    # ------------------------------------------------------------------
    # 2. Parse .m mapping for this FC layer
    # ------------------------------------------------------------------
    layer_name = f"FC{layer_idx}"
    mm   = MaestroClusterMapper()
    mapping_available = True
    try:
        dims, mapping = mm.map_layer_from_file(mapping_file, layer_name=layer_name)
    except ValueError as e:
        # Keep exact quantized math active even if mapping data for this layer
        # is not present in the .m file.
        mapping_available = False
        dims, mapping = None, None
        if verbose:
            print(f"  [WARN] FC{layer_idx}: {e}. Skipping mapper/scheduler simulation.")

    total_pes  = int(mpe.num_pes)
    total_macs = shape_in * shape_out
    if mapping_available:
        latency_estimate = estimate_latency_objective(
            dims,
            mapping,
            total_pes=total_pes,
            config=LATENCY_CONFIG,
        )
    else:
        latency_estimate = estimate_fc_latency_objective(
            shape_in=shape_in,
            shape_out=shape_out,
            total_pes=total_pes,
            config=LATENCY_CONFIG,
        )

    # ------------------------------------------------------------------
    # 3. Build weight provider and iterate scheduler ops
    #
    # weight_provider(k0, kN) → (C, kN-k0) float32
    #   rows = patch_len = C (since R=S=1 for FC)
    #   cols = K-chunk width (≤ PE_OUT_COLS = 32)
    # ------------------------------------------------------------------
    weight_provider = make_weight_provider(params)
    scheduler       = MaestroClusterScheduler()
    programmed_pes  = set()
    programmed_modes = set()
    compute_count   = 0

    if mapping_available:
        for op in scheduler.iter_ops(dims, mapping, weight_provider):

            if op.op == "PROGRAM_CLUSTER":
                pe_id   = int(op.info["pe_id"]) % total_pes
                # Program signed INT8 so CrossbarArray enters PWM_INT8_ROW_SERIAL
                # mode and performs 4-way nibble banking internally.
                tile_32 = np.clip(
                    np.rint(np.asarray(op.info["weight_tile"], dtype=np.float32)),
                    -128,
                    127,
                ).astype(np.int8)
                mpe.program_weights_one(pe_id, tile_32)
                programmed_pes.add(pe_id)
                mode = str(getattr(mpe.pes[pe_id].crossbar, "mode", "UNKNOWN"))
                programmed_modes.add(mode)

            elif op.op == "COMPUTE_CLUSTER_C":
                pe_id   = int(op.info["pe_id"]) % total_pes
                c_start = int(op.info["c_start"])
                c_end   = int(op.info["c_end"])
                # Build TILE-element activation slice for PWM path.
                vec = np.zeros(TILE, dtype=np.uint8)
                span = min(c_end - c_start, TILE, shape_in - c_start)
                if span > 0:
                    vec[:span] = np.clip(x_adj[c_start:c_start + span], 0, 255).astype(np.uint8)
                mpe.compute_pe_fast(pe_id, vec)
                compute_count += 1

    if ENFORCE_PWM_MODE and mapping_available:
        allowed = {"PWM_INT8_ROW_SERIAL"}
        bad_modes = sorted(m for m in programmed_modes if m not in allowed)
        if bad_modes:
            raise RuntimeError(
                f"FC{layer_idx}: expected PWM_INT8_ROW_SERIAL programming, "
                f"found modes={sorted(programmed_modes)}"
            )

    # ------------------------------------------------------------------
    # 4. Exact quantised computation
    # ------------------------------------------------------------------
    y_int8 = torch_quantised_linear_forward_vectorised(
        input_data=x_adj,
        weights=params['W_int8'],
        bias=params['bias_int32'],
        requant_multiplier=params['requant_mult'],
        requant_shift=params['requant_shift'],
        output_zeropoint=output_zp,
        output_dtype=np.int8,
    )

    # ------------------------------------------------------------------
    # 5. Dequantise to float32
    # ------------------------------------------------------------------
    y_float = (y_int8.astype(np.float32) - output_zp) * params['output_scale']

    # ------------------------------------------------------------------
    # 6. L2 Buffer — store output, evict previous layer
    # ------------------------------------------------------------------
    l2_buffer.write_output_channel(layer_idx, 0, y_float)
    if layer_idx > 0:
        l2_buffer.clear_layer(layer_idx - 1)

    # ------------------------------------------------------------------
    # 7. Stats
    # ------------------------------------------------------------------
    if mapping_available:
        active_pes = min(len(programmed_pes), total_pes)
    else:
        tiles_k = int(np.ceil(shape_out / TILE))
        tiles_c = int(np.ceil(shape_in / TILE))
        active_pes = min(tiles_k * tiles_c, total_pes)
    util_pct   = 100.0 * active_pes / total_pes if total_pes > 0 else 0.0

    stats = {
        'ops':         total_macs,
        'num_weights': shape_in * shape_out,
        'active_pes':  active_pes,
        'total_pes':   total_pes,
        'util_pct':    util_pct,
        'modes':       sorted(programmed_modes) if programmed_modes else [],
        'latency_cycles': latency_estimate.latency_objective,
        'latency_objective': latency_estimate.latency_objective,
        'normalized_latency': latency_estimate.normalized_latency,
        'latency_breakdown': latency_estimate.as_dict(),
    }

    if verbose:
        print(
            f"  [FC{layer_idx}] {shape_in}→{shape_out} | "
            f"MACs={total_macs:,} | "
            f"PEs={active_pes}/{total_pes} ({util_pct:.1f}%) | "
            f"compute_ops={compute_count} | "
            f"latency={stats['latency_cycles']:,} cyc "
            f"(norm={stats['normalized_latency']:.6f}) | "
            f"modes={stats['modes'] if stats['modes'] else ['N/A']} | "
            f"out=[{y_float.min():.4f}, {y_float.max():.4f}]"
        )

    return y_float, y_int8, stats


# =====================================================
# Main
# =====================================================

def main():
    base          = Path(__file__).parent
    schema_path   = base / 'schema.json'
    test_path     = base / 'test_cases.json'
    mapping_file  = str(base / 'schema_10layer_mapping_fc.m')

    print("=" * 70)
    print("QUANTLINEAR INFERENCE PIPELINE")
    print("=" * 70)

    # Load model and test data
    layers_raw = load_schema(str(schema_path))
    test_data  = load_test_cases(str(test_path))
    layers     = [parse_layer(l) for l in layers_raw]

    print(f"Loaded {len(layers)} QuantLinear layers from schema.json")
    print(f"Loaded {len(test_data['examples'])} test cases from test_cases.json")
    print(f"Mapping file : {mapping_file}")
    print(f"Crossbar size: {TILE}×{TILE}\n")

    # -------------------------------------------------------------------------
    # Hardware setup — 32×32 crossbar PEs
    # -------------------------------------------------------------------------
    NUM_PES   = 512
    mpe       = MultiPENeuromorphicCore(
        num_pes=NUM_PES, input_size=TILE, output_size=TILE, iterations=0
    )
    l2_buffer = L2_Buffer(capacity=2_000_000, name="Global_L2")

    # Print model architecture
    print("Model Architecture:")
    for i, p in enumerate(layers):
        print(
            f"  FC{i}: {p['shape_in']:>4} → {p['shape_out']:<4}  "
            f"act={str(p['act_func']):<6}  "
            f"input_no_quant={p['input_no_quant']}"
        )
    print()

    # -------------------------------------------------------------------------
    # Run inference for each test case
    # -------------------------------------------------------------------------
    results = []
    latency_results = []

    # When VERIFY_LAYER is set, run only that single layer.
    layers_to_run = (
        [(VERIFY_LAYER, layers[VERIFY_LAYER])]
        if VERIFY_LAYER is not None
        else list(enumerate(layers))
    )

    # Optional per-layer detailed logs (one file per FC layer).
    layer_log_handles: dict[int, io.TextIOWrapper] = {}
    layer_log_stats: dict[int, dict] = {}
    layer_logs_dir = base / "layer_logs"

    if GENERATE_LAYER_LOGS:
        layer_logs_dir.mkdir(exist_ok=True)
        for layer_idx, params in layers_to_run:
            log_path = layer_logs_dir / f"FC{layer_idx}_detailed_log.txt"
            fh = open(log_path, "w", encoding="utf-8")
            fh.write(f"FC{layer_idx} DETAILED LOG\n")
            fh.write("=" * 120 + "\n")
            fh.write(f"Layer shape: {params['shape_in']} -> {params['shape_out']}\n")
            fh.write(f"Num examples: {len(test_data['examples'])}\n")
            fh.write("=" * 120 + "\n\n")
            layer_log_handles[layer_idx] = fh
            layer_log_stats[layer_idx] = {
                "count": 0,
                "sum_max_err": 0.0,
                "sum_mean_err": 0.0,
                "max_max_err": 0.0,
                "sum_max_q_err": 0,
                "max_max_q_err": 0,
                "sum_nz_qdiff": 0,
                "sum_latency_cycles": 0,
                "max_latency_cycles": 0,
            }

    for ex_idx, example in enumerate(test_data['examples']):
        print(f"Test Case {ex_idx + 1}/{len(test_data['examples'])}:")

        # Reset L2 buffer between test cases
        l2_buffer.clear_all()

        # First entry is the raw int8 input
        x_current = np.array(example[0]['output'], dtype=np.int8)

        all_pass = True
        example_latency_cycles = 0

        for layer_idx, params in layers_to_run:
            y_float, y_int8, stats = execute_quant_linear(
                layer_idx=layer_idx,
                params=params,
                x_int8=x_current,
                mapping_file=mapping_file,
                mpe=mpe,
                l2_buffer=l2_buffer,
                verbose=True,
            )
            x_current = y_int8
            example_latency_cycles += int(stats["latency_cycles"])

            # Compare against expected float32 output and quantized grid.
            expected = np.array(example[layer_idx + 1]['output'], dtype=np.float32)
            float_abs_diff = np.abs(y_float - expected)
            max_err  = float(np.max(float_abs_diff))
            mean_err = float(np.mean(float_abs_diff))

            expected_q = np.rint(expected / params['output_scale'] + params['output_zp'])
            expected_q = np.clip(expected_q, -128, 127).astype(np.int8)
            int8_diff  = y_int8.astype(np.int16) - expected_q.astype(np.int16)
            q_abs_err  = np.abs(int8_diff)
            max_q_err  = int(np.max(q_abs_err))
            mean_q_err = float(np.mean(q_abs_err))
            mismatch_idx = np.where(int8_diff != 0)[0]

            # Allow 1 LSB to absorb tie-rounding drift across exporters.
            ok       = max_q_err <= 1
            all_pass = all_pass and ok

            status = "PASS" if ok else "FAIL"
            print(
                f"  [{status}] FC{layer_idx} "
                f"({params['shape_in']} \u2192 {params['shape_out']}): "
                f"max_err={max_err:.7f}  mean_err={mean_err:.7f}  "
                f"max_q_err={max_q_err}  mean_q_err={mean_q_err:.3f}  "
                f"modes={stats['modes'] if stats['modes'] else ['N/A']}  "
                f"PEs={stats['active_pes']}/{stats['total_pes']} "
                f"({stats['util_pct']:.1f}%)  "
                f"latency_obj={stats['latency_objective']:,} cyc"
            )

            if GENERATE_LAYER_LOGS and layer_idx in layer_log_handles:
                st = layer_log_stats[layer_idx]
                st["count"] += 1
                st["sum_max_err"] += max_err
                st["sum_mean_err"] += mean_err
                st["max_max_err"] = max(st["max_max_err"], max_err)
                st["sum_max_q_err"] += max_q_err
                st["max_max_q_err"] = max(st["max_max_q_err"], max_q_err)
                st["sum_nz_qdiff"] += int(mismatch_idx.size)
                st["sum_latency_cycles"] += int(stats["latency_cycles"])
                st["max_latency_cycles"] = max(
                    st["max_latency_cycles"],
                    int(stats["latency_cycles"]),
                )

                fh = layer_log_handles[layer_idx]
                fh.write("-" * 120 + "\n")
                fh.write(f"Example {ex_idx + 1}/{len(test_data['examples'])}\n")
                fh.write("-" * 120 + "\n")
                fh.write(
                    f"max_err={max_err:.9f}, mean_err={mean_err:.9f}, "
                    f"max_q_err={max_q_err}, mean_q_err={mean_q_err:.6f}, "
                    f"modes={stats['modes'] if stats['modes'] else ['N/A']}, "
                    f"PEs={stats['active_pes']}/{stats['total_pes']} ({stats['util_pct']:.1f}%), "
                    f"latency_obj={stats['latency_objective']} cycles, "
                    f"normalized_latency={stats['normalized_latency']:.9f}, "
                    f"latency_breakdown={stats['latency_breakdown']}\n\n"
                )
                fh.write(f"actual_float (len={y_float.size}):\n{_arr_to_str(y_float)}\n\n")
                fh.write(f"expected_float (len={expected.size}):\n{_arr_to_str(expected)}\n\n")
                fh.write(f"float_abs_diff:\n{_arr_to_str(float_abs_diff)}\n\n")
                fh.write(f"actual_int8 (len={y_int8.size}):\n{_arr_to_str(y_int8)}\n\n")
                fh.write(
                    f"expected_int8_from_expected_float (len={expected_q.size}):\n"
                    f"{_arr_to_str(expected_q)}\n\n"
                )
                fh.write(f"int8_diff (actual - expected):\n{_arr_to_str(int8_diff)}\n\n")
                fh.write(f"mismatch_indices (count={mismatch_idx.size}): {mismatch_idx.tolist()}\n")
                if mismatch_idx.size > 0:
                    fh.write(
                        "mismatch_rows: idx | actual_i8 | expected_i8 | "
                        "actual_f | expected_f | abs_f_diff\n"
                    )
                    for idx in mismatch_idx.tolist():
                        fh.write(
                            f"  {idx:4d} | {int(y_int8[idx]):9d} | {int(expected_q[idx]):11d} | "
                            f"{float(y_float[idx]): .9f} | {float(expected[idx]): .9f} | "
                            f"{float(float_abs_diff[idx]):.9f}\n"
                        )
                fh.write("\n\n")

        outcome = "ALL PASS" if all_pass else "SOME FAILURES"
        print(f"  \u2192 {outcome} | latency_obj={example_latency_cycles:,} cycles\n")
        results.append(all_pass)
        latency_results.append(example_latency_cycles)

    if GENERATE_LAYER_LOGS:
        for layer_idx, fh in layer_log_handles.items():
            st = layer_log_stats[layer_idx]
            c = max(st["count"], 1)
            fh.write("=" * 120 + "\n")
            fh.write("SUMMARY\n")
            fh.write("=" * 120 + "\n")
            fh.write(
                f"avg_max_err={st['sum_max_err']/c:.9f}, "
                f"avg_mean_err={st['sum_mean_err']/c:.9f}, "
                f"worst_max_err={st['max_max_err']:.9f}, "
                f"avg_max_q_err={st['sum_max_q_err']/c:.6f}, "
                f"worst_max_q_err={st['max_max_q_err']}, "
                f"avg_nonzero_qdiff={st['sum_nz_qdiff']/c:.3f}, "
                f"avg_latency_cycles={st['sum_latency_cycles']/c:.3f}, "
                f"worst_latency_cycles={st['max_latency_cycles']}\n"
            )
            fh.close()

    # -------------------------------------------------------------------------
    # Final summary
    # -------------------------------------------------------------------------
    l2_stats = l2_buffer.get_stats()

    print("=" * 70)
    print(f"SUMMARY: {sum(results)}/{len(results)} test cases passed")
    if latency_results:
        print(
            f"Latency objective: avg={np.mean(latency_results):,.1f} cycles | "
            f"worst={max(latency_results):,} cycles"
        )
    print()
    print(
        f"L2 Buffer: capacity={l2_stats['capacity']:,} | "
        f"writes={l2_stats['write_count']:,} | "
        f"reads={l2_stats['read_count']:,} | "
        f"utilisation={l2_stats['utilization']:.1f}%"
    )
    print("=" * 70)
    if GENERATE_LAYER_LOGS:
        print(f"Layer logs written to: {layer_logs_dir.resolve()}")
     
     # Read and display layer 0 output from L2 buffer
    print("Layer 0 output from L2 Buffer:")
    layer0_out = l2_buffer.read_output_channel(0, 0)
    if layer0_out is not None:
       print(f"  Shape: {layer0_out.shape}")
       print(f"  Min:   {layer0_out.min():.6f}")
       print(f"  Max:   {layer0_out.max():.6f}")
       print(f"  Non-zero: {np.count_nonzero(layer0_out)}/{len(layer0_out)}")
       print(f"  Values: {layer0_out}")
    else:
        print("  (not found — may have been evicted)")



if __name__ == "__main__":
    main()
