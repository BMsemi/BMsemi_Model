from __future__ import annotations

from dataclasses import asdict, dataclass
import json
from pathlib import Path
import time
from typing import Any

from .fingerprint import ImageIdentity
from .pe_tcam import (
    DualPETcamSearch,
    ENTRIES_PER_PE,
    FULL_CARE,
    LOGICAL_BITS,
    PE_COUNT,
    PHYSICAL_COLUMNS,
    PHYSICAL_ROWS,
    TOTAL_ENTRIES,
    TOTAL_ENGINE_COUNT,
    TcamEntry,
    TcamMatch,
    YOLO_LAYER0_ENGINE_COUNT,
)


@dataclass(frozen=True)
class CacheLookup:
    hit: bool
    payload: dict[str, Any] | None
    match: TcamMatch | None
    candidate_count: int
    reason: str


class PersistentRagCache:
    """Persist TCAM metadata and YOLO detection chunks in PS-accessible storage."""

    SCHEMA_VERSION = 1

    def __init__(self, directory: str | Path, searcher: DualPETcamSearch) -> None:
        self.directory = Path(directory)
        self.directory.mkdir(parents=True, exist_ok=True)
        self.chunk_directory = self.directory / "chunks"
        self.chunk_directory.mkdir(exist_ok=True)
        self.index_path = self.directory / "index.json"
        self.searcher = searcher
        self._records = self._load()
        self._program_searcher()

    def _load(self) -> list[dict[str, Any]]:
        if not self.index_path.exists():
            return []
        document = json.loads(self.index_path.read_text(encoding="utf-8"))
        if int(document.get("schema_version", -1)) != self.SCHEMA_VERSION:
            raise ValueError("Unsupported TCAM RAG cache schema.")
        records = list(document.get("entries", []))
        if len(records) > TOTAL_ENTRIES:
            raise ValueError("TCAM RAG index exceeds the 32-entry PE capacity.")
        return records

