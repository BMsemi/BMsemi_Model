    def manifest_metadata(self) -> dict[str, Any]:
        return self._manifest_metadata()

    def _save(self) -> None:
        document = {
            "schema_version": self.SCHEMA_VERSION,
            **self._manifest_metadata(),
            "capacity": TOTAL_ENTRIES,
            "entries": sorted(self._records, key=lambda item: int(item["slot"])),
        }
        temporary = self.index_path.with_suffix(".json.tmp")
        temporary.write_text(json.dumps(document, indent=2), encoding="utf-8")
        temporary.replace(self.index_path)

    def _program_searcher(self) -> None:
        self.searcher.program(
            TcamEntry(
                slot=int(record["slot"]),
                key=int(record["visual_key"]),
                care=FULL_CARE,
                chunk_id=int(record["chunk_id"]),
            )
            for record in self._records
        )

    def lookup(
        self,
        identity: ImageIdentity,
        *,
        max_hamming_distance: int = 0,
    ) -> CacheLookup:
        if not self._records:
            return CacheLookup(False, None, None, 0, "empty_cache")
        matches = self.searcher.search(identity.visual_key, top_k=TOTAL_ENTRIES)
        candidates = [
            match
            for match in matches
            if match.hamming_distance <= int(max_hamming_distance)
        ]
        records = {int(record["slot"]): record for record in self._records}
        for match in candidates:
            record = records[match.slot]
            # TCAM narrows the search. The full digest is the cache-validity guard.
            if str(record["sha256"]) != identity.sha256:
                continue
            chunk_path = self.directory / str(record["chunk_file"])
            payload = json.loads(chunk_path.read_text(encoding="utf-8"))
            record["last_access_ns"] = time.time_ns()
            self._save()
            return CacheLookup(True, payload, match, len(candidates), "digest_verified")
        reason = "digest_mismatch" if candidates else "tcam_distance_miss"
        return CacheLookup(False, None, candidates[0] if candidates else None, len(candidates), reason)

    def insert(
        self,
        identity: ImageIdentity,
        payload: dict[str, Any],
        *,
        image_name: str,
    ) -> TcamEntry:
        now = time.time_ns()
        existing = next(
            (record for record in self._records if record["sha256"] == identity.sha256),
            None,
        )
        if existing is not None:
            slot = int(existing["slot"])
            chunk_id = int(existing["chunk_id"])
            self._records.remove(existing)
        elif len(self._records) < TOTAL_ENTRIES:
            occupied = {int(record["slot"]) for record in self._records}
            slot = next(index for index in range(TOTAL_ENTRIES) if index not in occupied)
            chunk_id = slot + 1
        else:
            victim = min(self._records, key=lambda record: int(record["last_access_ns"]))
            slot = int(victim["slot"])
            chunk_id = int(victim["chunk_id"])
            self._records.remove(victim)

        chunk_relative = Path("chunks") / f"chunk_{chunk_id:08x}.json"
        chunk_path = self.directory / chunk_relative
        chunk_path.write_text(json.dumps(payload, indent=2), encoding="utf-8")
        self._records.append(
            {
                "slot": slot,
                "visual_key": identity.visual_key,
                "care": FULL_CARE,
                "chunk_id": chunk_id,
                "sha256": identity.sha256,
                "byte_count": identity.byte_count,
                "image_name": image_name,
                "chunk_file": chunk_relative.as_posix(),
                "last_access_ns": now,
            }
        )
        self._save()
        self._program_searcher()
        return TcamEntry(slot, identity.visual_key, FULL_CARE, chunk_id)

    def diagnostics(self) -> dict[str, Any]:
        return {
            **self._manifest_metadata(),
            "cache_dir": str(self.directory),
            "index_path": str(self.index_path),
            "chunk_dir": str(self.chunk_directory),
            "entry_count": len(self._records),
            "capacity": TOTAL_ENTRIES,
            "entries": [dict(record) for record in self._records],
            "hardware_searches": self.searcher.searches,
            "pe_launches": self.searcher.pe_launches,
            "transaction_shape": [32, self.searcher.column_window],
        }
